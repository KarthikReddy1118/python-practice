import numpy as np
arr=np.array([10,20,30,40,50])
print(arr)

print("addition with 10:" , arr+10) #addition with 10  
print("subtraction with 10:" , arr-10) #subtraction with 10
print("multiplication with 10:" , arr*10) #multiplication with 10
print("power with 2:",arr**2) #power with 2

''' like this you can perform all the arthematic operations in numpy with the help of operators like +,-,*,/,** etc. and also you can perform the same operations with two arrays of same size'''