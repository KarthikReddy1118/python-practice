import numpy as np
arr=np.array([10,20,30,40,50])
print("mean:",np.mean(arr))
print("maximum number of arrayis:",np.max(arr))
print("minimum number of arrayis:",np.min(arr))
print("sum of all elements in array is:",np.sum(arr))
print("standard deviation of array is:",np.std(arr))
print("variance of array is:",np.var(arr))
print("median of array is:",np.median(arr))
